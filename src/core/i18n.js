const pick = (lang) => (String(lang || '').toLowerCase().startsWith('ko') ? 'ko' : 'en');
let current = pick(typeof navigator !== 'undefined' ? navigator.language : 'en');
const warned = new Set();

export function setLang(lang) {
  current = pick(lang);
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  const entry = MESSAGES[key];
  if (!entry) {
    // 빠진 키는 화면에 키 이름이 그대로 보이므로 콘솔에도 한 번 남긴다.
    if (!warned.has(key)) console.warn(`frame-mesh: missing message "${key}"`);
    warned.add(key);
    return key;
  }
  const text = entry[LANGS.indexOf(current)] ?? entry[0];
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
}

// 정적 HTML의 data-i18n(글자), data-i18n-title, data-i18n-placeholder 속성을 현재 언어로 채운다.
export function applyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
